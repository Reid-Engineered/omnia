//! Static built-in part catalog and resolved library definitions (`P1.4`; `PB1`, `PD7`, `PD11`,
//! `PINV10`).

use std::sync::Arc;

use omnia_doc::{
    EmbeddedParamSpec, EmbeddedPartDef, EmbeddedPin, EmbeddedSimBinding, FiniteF64, ParamKind,
    ParamValue, PinRole, PrimitiveKind, Pt, Rect, SupplyDecl, SymbolId,
};

use crate::{ContentHash, LibraryError};

/// Licence metadata for a resolved library part (`PD4`, `PK11`).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct LicenseInfo {
    pub spdx: Arc<str>,
    pub source: Option<Arc<str>>,
}

/// Resolved, verified library part definition (plan section 10).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PartDef {
    pub source_id: Arc<str>,
    pub content_hash: ContentHash,
    pub tags: Vec<Arc<str>>,
    pub datasheet: Option<Arc<str>>,
    pub license: Option<LicenseInfo>,
    pub embedded: Arc<EmbeddedPartDef>,
}

/// Static pin record generated by `cargo xtask parts`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct BuiltinPin {
    pub number: &'static str,
    pub name: &'static str,
    pub role: PinRole,
}

/// Static parameter kind generated by `cargo xtask parts`. Real bounds are stored as raw IEEE-754
/// bit patterns of validated [`FiniteF64`] values so the table stays `const` with exact fidelity.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum BuiltinParamKind {
    Real {
        unit: Option<&'static str>,
        min_bits: Option<u64>,
        max_bits: Option<u64>,
    },
    Int {
        min: Option<i64>,
        max: Option<i64>,
    },
    Bool,
    Enum(&'static [&'static str]),
    Text,
}

/// Static parameter default value generated by `cargo xtask parts`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum BuiltinParamValue {
    Real { raw: &'static str, value_bits: u64 },
    Int(i64),
    Bool(bool),
    Enum(&'static str),
    Text(&'static str),
}

/// Static parameter specification generated by `cargo xtask parts`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct BuiltinParamSpec {
    pub name: &'static str,
    pub label: &'static str,
    pub kind: BuiltinParamKind,
    pub default: BuiltinParamValue,
    pub optional: bool,
}

/// Static supply declaration generated by `cargo xtask parts` (`PD5`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct BuiltinSupplyDecl {
    pub pos: u16,
    pub neg: u16,
    pub implicit_bits: Option<(u64, u64)>,
}

/// Static simulation binding generated by `cargo xtask parts`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum BuiltinSimBinding {
    None,
    Primitive {
        kind: PrimitiveKind,
        terminals: &'static [u16],
    },
    Model {
        spice_prefix: char,
        entry: &'static str,
        terminals: &'static [u16],
        spice: &'static str,
        supply: Option<BuiltinSupplyDecl>,
    },
    Subckt {
        entry: &'static str,
        terminals: &'static [u16],
        spice: &'static str,
        supply: Option<BuiltinSupplyDecl>,
    },
}

/// Static licence record generated by `cargo xtask parts`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct BuiltinLicense {
    pub spdx: &'static str,
    pub source: Option<&'static str>,
}

/// Static compiled built-in part record emitted into `generated.rs` by `cargo xtask parts` (`PD7`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct BuiltinPart {
    pub id: &'static str,
    pub source_id: &'static str,
    pub content_hash: [u8; 32],
    pub name: &'static str,
    pub category: &'static str,
    pub description: &'static str,
    pub tags: &'static [&'static str],
    pub datasheet: Option<&'static str>,
    pub designator_prefix: &'static str,
    pub symbol: SymbolId,
    pub symbol_default: bool,
    pub local_pins: &'static [Pt],
    pub local_bounds: Rect,
    pub pins: &'static [BuiltinPin],
    pub params: &'static [BuiltinParamSpec],
    pub primary_param: Option<&'static str>,
    pub sim: BuiltinSimBinding,
    pub license: Option<BuiltinLicense>,
}

fn finite_from_bits(bits: u64) -> FiniteF64 {
    FiniteF64::new(f64::from_bits(bits)).expect("compiled builtin FiniteF64 must be finite")
}

impl BuiltinSupplyDecl {
    fn to_supply_decl(self) -> SupplyDecl {
        SupplyDecl {
            pos: self.pos,
            neg: self.neg,
            implicit: self
                .implicit_bits
                .map(|(pos, neg)| (finite_from_bits(pos), finite_from_bits(neg))),
        }
    }
}

impl BuiltinParamSpec {
    fn to_embedded(self) -> EmbeddedParamSpec {
        let kind = match self.kind {
            BuiltinParamKind::Real {
                unit,
                min_bits,
                max_bits,
            } => ParamKind::Real {
                unit: unit.map(Arc::from),
                min: min_bits.map(finite_from_bits),
                max: max_bits.map(finite_from_bits),
            },
            BuiltinParamKind::Int { min, max } => ParamKind::Int { min, max },
            BuiltinParamKind::Bool => ParamKind::Bool,
            BuiltinParamKind::Enum(variants) => {
                ParamKind::Enum(variants.iter().copied().map(Arc::from).collect())
            }
            BuiltinParamKind::Text => ParamKind::Text,
        };
        let default = match self.default {
            BuiltinParamValue::Real { raw, value_bits } => ParamValue::Real {
                raw: Arc::from(raw),
                value: finite_from_bits(value_bits),
            },
            BuiltinParamValue::Int(v) => ParamValue::Int(v),
            BuiltinParamValue::Bool(v) => ParamValue::Bool(v),
            BuiltinParamValue::Enum(v) => ParamValue::Enum(Arc::from(v)),
            BuiltinParamValue::Text(v) => ParamValue::Text(Arc::from(v)),
        };
        EmbeddedParamSpec {
            name: Arc::from(self.name),
            label: Arc::from(self.label),
            kind,
            default,
            optional: self.optional,
        }
    }
}

impl BuiltinPart {
    /// Materialises the full [`PartDef`] and its [`EmbeddedPartDef`] from static data.
    pub fn to_part_def(&self) -> PartDef {
        let source_id: Arc<str> = Arc::from(self.source_id);
        let sim = match self.sim {
            BuiltinSimBinding::None => EmbeddedSimBinding::None,
            BuiltinSimBinding::Primitive { kind, terminals } => EmbeddedSimBinding::Primitive {
                kind,
                terminals: terminals.to_vec(),
            },
            BuiltinSimBinding::Model {
                spice_prefix,
                entry,
                terminals,
                spice,
                supply,
            } => EmbeddedSimBinding::Model {
                spice_prefix,
                entry: Arc::from(entry),
                terminals: terminals.to_vec(),
                spice: Arc::from(spice),
                supply: supply.map(BuiltinSupplyDecl::to_supply_decl),
            },
            BuiltinSimBinding::Subckt {
                entry,
                terminals,
                spice,
                supply,
            } => EmbeddedSimBinding::Subckt {
                entry: Arc::from(entry),
                terminals: terminals.to_vec(),
                spice: Arc::from(spice),
                supply: supply.map(BuiltinSupplyDecl::to_supply_decl),
            },
        };
        let embedded = EmbeddedPartDef {
            source_id: source_id.clone(),
            content_hash: Some(self.content_hash),
            name: Arc::from(self.name),
            category: Arc::from(self.category),
            description: Arc::from(self.description),
            designator_prefix: Arc::from(self.designator_prefix),
            symbol: self.symbol,
            local_pins: self.local_pins.to_vec(),
            local_bounds: self.local_bounds,
            pins: self
                .pins
                .iter()
                .map(|pin| EmbeddedPin {
                    number: Arc::from(pin.number),
                    name: Arc::from(pin.name),
                    role: pin.role,
                })
                .collect(),
            params: self
                .params
                .iter()
                .copied()
                .map(BuiltinParamSpec::to_embedded)
                .collect(),
            primary_param: self.primary_param.map(Arc::from),
            sim,
        };
        PartDef {
            source_id,
            content_hash: ContentHash(self.content_hash),
            tags: self.tags.iter().copied().map(Arc::from).collect(),
            datasheet: self.datasheet.map(Arc::from),
            license: self.license.map(|lic| LicenseInfo {
                spdx: Arc::from(lic.spdx),
                source: lic.source.map(Arc::from),
            }),
            embedded: Arc::new(embedded),
        }
    }
}

/// Component library catalog holding static compiled built-ins (`PB1`, `PINV10`).
#[derive(Debug, Clone)]
pub struct Catalog {
    builtins: &'static [BuiltinPart],
}

impl Catalog {
    /// Returns the static built-in catalog compiled at build time (`PB1`, `PINV10`).
    ///
    /// Executes zero filesystem reads and parses zero TOML at runtime.
    #[inline]
    pub const fn builtin() -> Self {
        Self {
            builtins: crate::generated::BUILTINS,
        }
    }

    /// Static slice of all compiled built-in parts in deterministic `source_id` order.
    #[inline]
    pub const fn builtins(&self) -> &'static [BuiltinPart] {
        self.builtins
    }

    /// Number of built-in parts in the catalog.
    #[inline]
    pub const fn len(&self) -> usize {
        self.builtins.len()
    }

    /// Returns `true` if the catalog has no parts.
    #[inline]
    pub const fn is_empty(&self) -> bool {
        self.builtins.is_empty()
    }

    /// Resolves a built-in part by canonical `source_id` (e.g. `"omnia:resistor"`) or bare
    /// built-in slug (e.g. `"resistor"`).
    pub fn resolve(&self, source_id: &str) -> Result<Arc<PartDef>, LibraryError> {
        self.builtins
            .iter()
            .find(|entry| entry.source_id == source_id || entry.id == source_id)
            .map(|entry| Arc::new(entry.to_part_def()))
            .ok_or_else(|| LibraryError::MissingEntry(source_id.to_owned()))
    }

    /// Returns the built-in default part definition for `symbol`, if one is declared (`PD11`).
    pub fn default_for_symbol(&self, symbol: SymbolId) -> Option<Arc<PartDef>> {
        self.builtins
            .iter()
            .find(|entry| entry.symbol == symbol && entry.symbol_default)
            .map(|entry| Arc::new(entry.to_part_def()))
    }
}

#[cfg(test)]
mod tests {
    use std::collections::BTreeMap;
    use std::path::Path;

    use omnia_doc::{EmbeddedSimBinding, FiniteF64, SupplyDecl, part_def::validate};
    use omnia_symbols::SymbolLibrary;

    use super::*;
    use crate::LibrarySource;

    /// `PINV10` / `PB1`: `Catalog::builtin()` is `const` and uses only static tables, doing zero
    /// filesystem I/O and zero TOML parsing at runtime.
    const STATIC_BUILTIN: Catalog = Catalog::builtin();

    #[test]
    fn ptc_builtin_load_pinv3_pinv10_pinv11() {
        let catalog = STATIC_BUILTIN;
        assert_eq!(catalog.len(), 8, "starter library has 8 built-in parts");
        let symbols = SymbolLibrary::builtin();

        // Every compiled built-in validates against omnia-doc PD10, matches omnia-symbols pins
        // (PINV3), and maps terminals bijectively (PINV11).
        let mut defaults_by_symbol: BTreeMap<SymbolId, Vec<&'static str>> = BTreeMap::new();
        for entry in catalog.builtins() {
            let def = catalog
                .resolve(entry.source_id)
                .expect("resolve by source_id");
            let by_slug = catalog.resolve(entry.id).expect("resolve by slug");
            assert_eq!(def, by_slug);
            assert_eq!(def.embedded.content_hash, Some(def.content_hash.0));

            let sym = symbols
                .try_get(def.embedded.symbol)
                .expect("valid built-in SymbolId");
            assert_eq!(def.embedded.local_bounds, sym.bounds);
            assert_eq!(def.embedded.pins.len(), sym.pins.len(), "PINV3 pin count");
            for (idx, (emb_pin, sym_pin)) in
                def.embedded.pins.iter().zip(sym.pins.iter()).enumerate()
            {
                assert_eq!(
                    &*emb_pin.number, sym_pin.number,
                    "PINV3 stored-pin-index order for {} pin {idx}",
                    entry.id
                );
                assert_eq!(def.embedded.local_pins[idx], sym_pin.at);
            }

            validate(&def.embedded).unwrap_or_else(|err| {
                panic!("built-in {} failed PD10 validate: {err}", entry.id);
            });

            if entry.symbol_default {
                defaults_by_symbol
                    .entry(entry.symbol)
                    .or_default()
                    .push(entry.id);
            }
        }

        // PTC-builtin-load: query resistor, diode-signal, opamp-generic.
        let resistor = catalog.resolve("resistor").expect("resistor present");
        assert_eq!(&*resistor.source_id, "omnia:resistor");
        assert!(
            resistor.embedded.sim.spice().is_none(),
            "PINV6: resistor primitive embeds no SPICE text"
        );
        assert_eq!(
            resistor.embedded.primary_param.as_deref(),
            Some("resistance")
        );

        let diode = catalog
            .resolve("diode-signal")
            .expect("diode-signal present");
        assert_eq!(&*diode.source_id, "omnia:diode-signal");
        assert!(matches!(
            diode.embedded.sim,
            EmbeddedSimBinding::Model {
                spice_prefix: 'D',
                ..
            }
        ));
        assert!(diode.embedded.sim.spice().is_some());

        let opamp = catalog
            .resolve("opamp-generic")
            .expect("opamp-generic present");
        assert_eq!(&*opamp.source_id, "omnia:opamp-generic");
        let opamp_sym = symbols.get(opamp.embedded.symbol);
        let idx_8 = opamp_sym
            .pins
            .iter()
            .position(|p| p.number == "8")
            .expect("opamp pin 8") as u16;
        let idx_4 = opamp_sym
            .pins
            .iter()
            .position(|p| p.number == "4")
            .expect("opamp pin 4") as u16;
        assert_eq!(
            opamp.embedded.sim.supply(),
            Some(&SupplyDecl {
                pos: idx_8,
                neg: idx_4,
                implicit: Some((
                    FiniteF64::new(15.0).unwrap(),
                    FiniteF64::new(-15.0).unwrap()
                )),
            }),
            "opamp-generic carries SupplyDecl with pins 8/4 and +/-15 V implicit fallback"
        );

        // PD11 / PTC-builtin-load: each starter default is the only default for its symbol.
        let starter_defaults = [
            ("Resistor-IEEE-Standard", "resistor"),
            ("Resistor-IEEE-Potentiometer", "potentiometer"),
            ("Capacitor-IEEE-NonPolarized", "capacitor"),
            ("Ground-COM-General", "ground"),
            ("Diode-COM-Standard", "diode-signal"),
            ("IC-COM-OpAmp", "opamp-generic"),
        ];
        assert_eq!(defaults_by_symbol.len(), starter_defaults.len());
        for (sym_name, expected_part_id) in starter_defaults {
            let sym_id = symbols.by_name(sym_name).expect(sym_name);
            assert_eq!(
                defaults_by_symbol.get(&sym_id).map(Vec::as_slice),
                Some(&[expected_part_id][..]),
                "symbol {sym_name} must have {expected_part_id} as its sole default"
            );
            let default_def = catalog
                .default_for_symbol(sym_id)
                .expect("default_for_symbol");
            assert_eq!(&*default_def.source_id, format!("omnia:{expected_part_id}"));
        }

        // Hashes match PK5 computed directly from the unpacked library/.
        let workspace_root = Path::new(env!("CARGO_MANIFEST_DIR"))
            .parent()
            .unwrap()
            .parent()
            .unwrap();
        let source = LibrarySource::open(&workspace_root.join("library")).expect("open library/");
        for path in source
            .paths()
            .filter(|p| p.starts_with("parts/") && p.ends_with(".toml"))
        {
            let resolved = source.resolve_part(path).expect("resolve library part");
            let compiled = catalog
                .resolve(resolved.part.id.as_str())
                .expect("compiled entry exists");
            assert_eq!(
                compiled.content_hash, resolved.content_hash,
                "PK5 hash mismatch for {}",
                resolved.part.id
            );
        }
    }
}
